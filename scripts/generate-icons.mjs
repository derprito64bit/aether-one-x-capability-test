import { writeFileSync } from 'node:fs'
import { Fragment } from 'react'

// Phosphor ships all six weights inside every icon (~0.9KB gzip each, ~28KB
// for this site's set), but the site uses one or two weights per icon. This
// copies only those weights' official path data out of @phosphor-icons/react
// into src/components/icons.tsx, rendered through Phosphor's own IconBase.
// Re-run after adding an icon or a weight:  node scripts/generate-icons.mjs
const ICONS = {
  ArrowLeft: ['bold'],
  ArrowRight: ['bold'],
  BellSimpleSlash: ['regular'],
  Bluetooth: ['regular', 'fill'],
  Camera: ['regular'],
  CaretLeft: ['bold'],
  ChatCircle: ['regular'],
  Check: ['bold'],
  CloudSun: ['regular'],
  FileText: ['regular'],
  Flashlight: ['regular', 'fill'],
  GearSix: ['regular'],
  HandPointing: ['regular'],
  Images: ['regular'],
  Info: ['regular'],
  Lightbulb: ['regular'],
  List: ['bold'],
  MagicWand: ['regular'],
  MapTrifold: ['regular'],
  Moon: ['regular', 'fill'],
  MusicNotes: ['regular'],
  Pause: ['fill'],
  Play: ['fill'],
  ShieldCheck: ['regular'],
  TextAlignLeft: ['regular'],
  Timer: ['regular'],
  Waveform: ['regular'],
  WifiHigh: ['regular', 'fill'],
  WifiSlash: ['regular'],
  X: ['bold'],
}

/** React element -> createElement source (Fragments flattened to children). */
function emit(el) {
  if (el === null || el === undefined || typeof el === 'boolean') return null
  const kids = [el.props?.children].flat().filter((c) => c !== null && c !== undefined)
  const parts = kids.map(emit).filter(Boolean)
  if (el.type === Fragment) return parts.join(', ')
  const props = Object.fromEntries(Object.entries(el.props).filter(([k]) => k !== 'children'))
  return `h(${JSON.stringify(el.type)}, ${JSON.stringify(props)}${parts.length ? `, ${parts.join(', ')}` : ''})`
}

const out = []
for (const [name, weights] of Object.entries(ICONS)) {
  // By file URL: the package's exports map does not expose dist/defs.
  const mod = await import(
    new URL(`../node_modules/@phosphor-icons/react/dist/defs/${name}.es.js`, import.meta.url).href
  )
  const map = mod.default
  const entries = weights.map((w) => {
    const el = map.get(w)
    if (el === undefined) throw new Error(`${name} has no ${w} weight`)
    return `['${w}', h(Fragment, null, ${emit(el)})]`
  })
  out.push(`export const ${name}Icon = icon('${name}Icon', [${entries.join(', ')}])`)
}

writeFileSync(
  'src/components/icons.tsx',
  `// Generated by scripts/generate-icons.mjs from @phosphor-icons/react: do not edit.
// Only the weights this site renders are bundled (Phosphor otherwise ships all
// six per icon). Add an icon or weight in the script's ICONS table and re-run.
/* eslint-disable */
import { IconBase, type IconProps, type IconWeight } from '@phosphor-icons/react'
import { Fragment, createElement as h, forwardRef, type ReactElement } from 'react'

function icon(name: string, entries: Array<[IconWeight, ReactElement]>) {
  const weights = new Map(entries)
  const first = entries[0]![0]
  const C = forwardRef<SVGSVGElement, IconProps>((props, ref) => {
    // A weight that was not bundled falls back instead of rendering empty.
    const asked = props.weight ?? 'regular'
    const weight = weights.has(asked) ? asked : first
    return h(IconBase, { ...props, ref, weight, weights })
  })
  C.displayName = name
  return C
}

${out.join('\n')}
`,
)
console.log(`wrote ${out.length} icons to src/components/icons.tsx`)
